"""A new job's or app's folder, as `mercury job new` and `mercury app new` write it (the SDN
platform design rev. 6, section 11a, item 3), and its Draft committed to a network's
repository. One home: `scripts/mercury` only parses its arguments and prints what this
answers, and J's JobProposal (part (b)) will call the same functions.

**What a folder holds** (`files(kind, ...)`, a mapping of each file's name to its text):
- `spec.yml`: the spec card. From a card given (`card_text`, validated first: a card holding
  an `ask:` question, or any refused field, is refused here, naming each, because the stub
  code and tests are written FROM the contract), or, with `blank`, an empty card
  (`templates/blank_spec.yml`), its every open field an `ask:` question, so `job check`
  refuses it by name until a person answers each;
- the code stub: `job.py`, a `Job` from the card's contract (`modules/jobs/base.py`'s `Job`
  and `JobMeta`; its `run` raises until written), or, for an app, `<name>.py`, its logic as
  plain functions;
- the tests: `test_job.py` (`test_app.py` for an app), one test per acceptance example, each
  `@covers` its example and failing until written (`assert False`, naming the example), so
  `job check`'s `tests` check fails naming each until a person or their assistant writes it;
- `conftest.py`, the fixed one (`templates/conftest.py.template`; the job fixtures carry the
  same file), so the folder runs unchanged under pytest;
- `AUTHORING.md`, the guide for a person's AI assistant (`templates/AUTHORING.md`);
- for an app, `manifest.yml` (`templates/manifest.yml`, the dns_blacklist manifest's shape).

**Where it goes:** `write(folder, files)` refuses a folder that exists and is not empty,
naming it, and writes nothing else. A job or app never lives in a network's configuration
repository, which holds its goldens and intent (the SDN design revision 7, code apart from state):
Mercury registers one as a Draft from the network's own code repository.

Nothing here parses an address: a card's inputs are typed by name (`HostRef`, `DeviceRef`),
never by an address, so there is no IPv4 or IPv6 case to give.
"""

import keyword
import os
import re
import textwrap

from modules.jobs import spec as spec_card
from modules.jobs.base import APP_NAME, JOB_NAME, ContractError

TEMPLATES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "templates")
AUTHORING = "AUTHORING.md"
CONFTEST = "conftest.py"
MANIFEST = "manifest.yml"
KINDS = ("job", "app")
#: The test file a kind's folder holds.
TEST_FILE = {"job": "test_job.py", "app": "test_app.py"}
#: The blank card's two examples (its every other field an `ask:`).
BLANK_EXAMPLES = ("the first example", "the second example")
#: A card's input type, as the stub's annotation (a datapath id is written as given: an
#: integer, `0x` hex, sixteen hex digits or eight colon-separated bytes, so a string).
_ANNOTATION = {"str": "str", "int": "int", "float": "float", "bool": "bool",
               "HostRef": "HostRef", "DeviceRef": "DeviceRef", "dpid": "str"}
_LIST = re.compile(r"^list\[([A-Za-z]+)\]$")
TEST_NAME_MAX = 60
#: The two lines that bound the gate's checks in AUTHORING.md (`gate_checks_markdown`).
CHECKS_BEGIN = "<!-- the gate's checks: generated by modules/jobs/scaffold.gate_checks_markdown -->"
CHECKS_END = "<!-- end of the gate's checks -->"
#: The two lines that bound the app allowlist's table in AUTHORING.md.
ALLOWLIST_BEGIN = ("<!-- the app allowlist: generated by "
                   "modules/jobs/scaffold.app_allowlist_markdown -->")
ALLOWLIST_END = "<!-- end of the app allowlist -->"
#: The two lines that bound the controller's Python tables in AUTHORING.md.
PYTHON_BEGIN = ("<!-- the controller's Python: generated by "
                "modules/jobs/scaffold.controller_python_markdown -->")
PYTHON_END = "<!-- end of the controller's Python -->"


class ScaffoldError(ContractError):
    """A folder `new` will not write, or a Draft it will not commit, naming why."""


def template(name: str) -> str:
    """The text of `templates/<name>`."""
    with open(os.path.join(TEMPLATES, name), encoding="utf-8") as fh:
        return fh.read()


def authoring_text() -> str:
    """AUTHORING.md as `new` writes it: the template, byte for byte."""
    return template(AUTHORING)


def gate_checks_markdown() -> str:
    """The authoring guide's list of the gate's checks, generated from the gates' own tables
    (`modules.jobs.gate.CHECKS`, `RULES`, `ACTIONS`, and the app gate's two checks), so a
    check added to the gate cannot be missing from the guide: tests/test_mercury_cli.py holds
    the template to containing exactly this, between `CHECKS_BEGIN` and `CHECKS_END`."""
    from modules.apps import gate as app_gate
    from modules.jobs import gate, mutate

    lines = [CHECKS_BEGIN, ""]
    for n, name in enumerate(gate.CHECKS, 1):
        action = gate.ACTIONS[name].format(ceiling=mutate.CEILING)
        lines += [f"{n}. **`{name}`.** {gate.RULES[name]}", "",
                  f"   > To clear it: {action}", ""]
        if name == "static":
            lines += ["   When a file itself is refused (a link, too large, not UTF-8, a name "
                      "that shadows an import, Python in a subfolder other than tests/):", "",
                      f"   > To clear it: {gate.FOLDER_ACTION}", ""]
    lines += ["A check that cannot run because an earlier one failed says \"not run\", and:", "",
              f"> To clear it: {gate.NOT_RUN_ACTION.format(first='<earlier>')}", "",
              "An app's verdict (`mercury app check`) runs no app code: it has `manifest` "
              "first and `reconcile` last, and its `static` check is the app allowlist's, not "
              "the job's:", ""]
    for name in ("manifest", "static"):
        lines += [f"- **`{name}`.** {app_gate.RULES[name]}", "",
                  f"  > To clear it: {app_gate.ACTIONS[name]}", ""]
        if name == "static":
            lines += ["  When the controller's Python is not known (\"can't tell\"):", "",
                      f"  > To clear it: {app_gate.PYTHON_ACTION}", ""]
    harness = [n for n in app_gate.APP_CHECKS if n in app_gate.HARNESS_CHECKS]
    named = ", ".join(f"`{n}`" for n in harness[:-1]) + f" and `{harness[-1]}`"
    lines += [f"- **`reconcile`.** {app_gate.RULES['reconcile']}", "",
              f"- {named} need the app's code run, in the container harness, never in the job "
              f"sandbox: until the harness lands each says \"{app_gate.HARNESS_NOT_RUN}\", so "
              "an app's verdict does not pass yet.", "",
              f"  > To clear it: {app_gate.HARNESS_ACTION}", "",
              "- `spec`, `examples` and `asserts` are the job gate's, read from the source.", "",
              CHECKS_END]
    return "\n".join(lines)


def app_allowlist_markdown() -> str:
    """The authoring guide's table of the app allowlist, generated from its one table
    (`modules.apps.allowlist.IMPORTS`), between `ALLOWLIST_BEGIN` and `ALLOWLIST_END`
    (tests/test_app_allowlist.py holds the template to it)."""
    from modules.apps import allowlist

    lines = [ALLOWLIST_BEGIN, "", "| Module | Why it is allowed | Refused of it |",
             "|---|---|---|"]
    refused = {}
    for module in sorted(allowlist.IMPORTS):
        rule = allowlist.IMPORTS[module]
        if not rule.allowed:
            refused.setdefault(rule.why, []).append(module)
            continue
        shown = f"`{module}`" + (" and its submodules" if rule.submodules else "")
        names = "; ".join(f"`{n}`: {why}" for n, why in sorted(rule.refused_names.items()))
        lines.append(f"| {shown} | {rule.why} | {names or 'its private (`_`) names'} |")
    lines += ["", "Refused by name (any module not in the table above is refused too):", ""]
    for why, modules in refused.items():
        lines.append(f"- {', '.join(f'`{m}`' for m in modules)}: {why}")
    lines += ["", ALLOWLIST_END]
    return "\n".join(lines)


def controller_python_markdown() -> str:
    """The authoring guide's tables of what an older controller Python lacks, generated from
    the app check's own tables (`modules.apps.python_versions`: `GRAMMAR`, `MODULES`, `NAMES`,
    `BUILTINS`), between `PYTHON_BEGIN` and `PYTHON_END` (tests/test_controller_python.py
    holds the template to it)."""
    from modules.apps import python_versions as V

    oldest = V.shown(V.OLDEST)
    lines = [PYTHON_BEGIN, "", "| Grammar | Needs | On an older controller, instead |",
             "|---|---|---|"]
    for feature in V.GRAMMAR:
        lines.append(f"| {feature.words} | {V.shown(V.available_from(feature.since))} | "
                     f"{feature.instead} |")
    lines += ["", f"What the standard library lacks before each version, from Python's "
                  f"documentation (\"New in version\"); a {oldest} controller lacks every row:",
              "", "| Needs | Modules, names and builtins |", "|---|---|"]
    by_minor = {}
    for table, kind in ((V.MODULES, " (module)"), (V.NAMES, ""), (V.BUILTINS, " (builtin)")):
        for dotted, docs in table.items():
            note = f" ({docs})" if docs != V.shown(V.available_from(docs)) else ""
            by_minor.setdefault(V.available_from(docs), []).append(f"`{dotted}`{kind}{note}")
    for minor in sorted(by_minor):
        lines.append(f"| {V.shown(minor)} | {', '.join(sorted(by_minor[minor]))} |")
    lines += ["", PYTHON_END]
    return "\n".join(lines)


# ── the names ────────────────────────────────────────────────────────────────────────────────

def name_rule(kind: str):
    return JOB_NAME if kind == "job" else APP_NAME


def check_name(kind: str, name: str, what: str) -> str:
    """*name* when it is a *kind*'s name, else `ScaffoldError` naming the rule."""
    if kind not in KINDS:
        raise ScaffoldError("the kind", [f"{kind!r} is not one of {', '.join(KINDS)}"])
    rule = name_rule(kind)
    if not isinstance(name, str) or not rule.fullmatch(name):
        whose = "a job's" if kind == "job" else "an app's"
        raise ScaffoldError(what, [f"{name!r} is not {whose} name: it matches {rule.pattern}"])
    return name


def class_name(name: str) -> str:
    """`switch-links` -> `SwitchLinks`, `dns_blacklist` -> `DnsBlacklist`."""
    return "".join(part.capitalize() for part in re.split(r"[-_]", name) if part)


def stub_test_name(example: str, taken: set) -> str:
    """The test function for *example*: `test_` and its words, unique among *taken*."""
    words = re.sub(r"[^a-z0-9]+", "_", example.lower()).strip("_")[:TEST_NAME_MAX].rstrip("_")
    base = f"test_{words or 'example'}"
    name, n = base, 2
    while name in taken or keyword.iskeyword(name):
        name, n = f"{base}_{n}", n + 1
    taken.add(name)
    return name


def _one_line(text: str) -> str:
    return " ".join(str(text).split())


def _literal(value) -> str:
    """*value* (a string or a list of strings) as a Python literal, double-quoted (JSON's
    string is a valid Python one: its escapes are Python's)."""
    import json

    return json.dumps(value)


def _docline(text: str) -> str:
    """*text* on one line, safe inside a triple-quoted docstring."""
    return _one_line(text).replace("\\", "/").replace('"""', "'''")


def _comment(label: str, text: str) -> list:
    wrapped = textwrap.wrap(f"{label}: {_one_line(text)}", width=88)
    return [f"    # {wrapped[0]}"] + [f"    #   {w}" for w in wrapped[1:]]


# ── the files ────────────────────────────────────────────────────────────────────────────────

def _annotation(kind: str) -> str:
    inner = _LIST.match(kind)
    if inner:
        return f"list[{_ANNOTATION[inner.group(1)]}]"
    return _ANNOTATION[kind]


def job_stub(card) -> str:
    """`job.py` for *card* (a `SpecCard`), its `run` raising until written."""
    cls = class_name(card.name)
    refs = sorted({t for f in card.inputs.values() for t in ("HostRef", "DeviceRef")
                   if t in f.type})
    imports = ", ".join(refs + ["Job", "JobInputs", "JobMeta", "Scope"])
    scope = (f"Scope(object_types={_literal(list(card.scope.object_types))}, "
             f"roles={_literal(list(card.scope.roles))})")
    lines = [
        f'"""{_docline(card.summary)}',
        "",
        "Written by `mercury job new` from spec.yml, whose contract this declares: write `run`",
        'and any helper beside it. AUTHORING.md says what `mercury job check` checks."""',
        "",
        f"from modules.jobs import {imports}",
        "",
        "",
        f"class {cls}(Job):",
        f"    meta = JobMeta(name={_literal(card.name)}, version=\"0.1.0\",",
        f"                   summary={_literal(_one_line(card.summary))},",
        f"                   permission={_literal(card.permission)},",
    ]
    if card.permission == "write":
        lines.append("                   # the most changes one run may plan: set it to the "
                     "job's reach")
        lines.append("                   max_changes=1,")
    lines += [
        f"                   scope={scope})",
        "",
        "    class Inputs(JobInputs):",
    ]
    if card.inputs:
        for name, field in card.inputs.items():
            note = f"  # {_one_line(field.description)}" if field.description else ""
            lines.append(f"        {name}: {_annotation(field.type)}{note}")
    else:
        lines.append('        """No inputs."""')
    outputs = ", ".join(f"{n} ({f.type})" for n, f in card.outputs.items()) or "none declared"
    lines += [
        "",
        "    def run(self, ctx, inputs):",
        f"        # spec.yml's outputs: {outputs}",
        "        raise NotImplementedError(\"run is not written yet: spec.yml's examples say "
        "what it does\")",
        "",
    ]
    return "\n".join(lines)


def app_stub(name: str, summary: str) -> str:
    """`<name>.py` for an app: its logic as plain functions over plain data, which the gate's
    runner tests without a controller."""
    return "\n".join([
        f'"""{_docline(summary) or "The app " + name + "."}',
        "",
        "Written by `mercury app new`. The app's logic, as plain functions over plain data, so",
        "`mercury app check` can test it without a controller: a decision per packet or event,",
        'given the config its manifest\'s config_schema declares. AUTHORING.md says more."""',
        "",
        "",
        "def decide(config, event):",
        '    """What the app does with *event*, given *config*."""',
        "    raise NotImplementedError(\"decide is not written yet: spec.yml's examples say what "
        "it does\")",
        "",
    ])


def stub_tests(kind: str, examples, subject: str) -> str:
    """The test file: one test per example (`(name, given, when, then, fixture)`), each
    `@covers` its example and failing until written. *subject* is what the tests import from
    the folder (`job`'s class, or the app module)."""
    module = "job" if kind == "job" else subject
    imported = class_name(subject) if kind == "job" else "decide"
    lines = [
        f'"""The tests of {subject}: one per acceptance example in spec.yml, each failing until it '
        "is",
        "written. pytest's format: `mercury " + kind + " check` runs them, and so does pytest "
        '(conftest.py)."""',
        "",
        f"from {module} import {imported}  # noqa: F401 - used once the tests are written",
        "from modules.jobs import covers",
    ]
    if kind == "job":
        lines.append("from modules.jobs.testing import plan_run  # noqa: F401 - the same")
    taken = set()
    for name, given, when, then, fixture in examples:
        param = "ryu" if fixture == "ryu_recorded" else ""
        lines += ["", "", f"@covers({_literal(name)})",
                  f"def {stub_test_name(name, taken)}({param}):"]
        lines += _comment("Given", given) + _comment("When", when) + _comment("Then", then)
        if fixture == "netbox_export":
            lines.append("    # The NetBox export (P1b) is not in the repository yet: give the "
                         "objects, netbox(job, objects={...}).")
        lines.append(f"    assert False, {_literal('not written yet: the example ' + repr(name))}")
    lines.append("")
    return "\n".join(lines)


def _blank_card(kind: str, name: str) -> str:
    return (template("blank_spec.yml").replace("@@KIND@@", kind).replace("@@NAME@@", name))


def manifest_text(name: str, summary: str) -> str:
    """`manifest.yml` for a new app, from the template (the dns_blacklist manifest's shape)."""
    import json

    return (template(MANIFEST).replace("@@NAME@@", name)
            .replace("@@SUMMARY@@", json.dumps(_one_line(summary))))


def files(kind: str, *, name: str = "", card_text: str = None, blank: bool = False) -> dict:
    """The new folder's files, `{name: text}` (see the module's docstring). Exactly one of
    *card_text* (a spec card's YAML) or *blank* (with *name*, the folder's name) is given."""
    if (card_text is None) == (not blank):
        raise ScaffoldError(f"{kind} new", ["give a spec card (--from) or --blank, one of "
                                            "them"])
    if blank:
        check_name(kind, name, "the folder's name")
        card_out, summary = _blank_card(kind, name), ""
        later = "spec.yml's example, once its questions are answered"
        examples = [(e, later, later, later, "") for e in BLANK_EXAMPLES]
        card = None
    else:
        card = spec_card.parse_spec(card_text, spec_card.SPEC)
        if card.kind != kind:
            raise ScaffoldError(spec_card.SPEC, [f"kind is {card.kind!r}: `mercury {kind} new` "
                                                 f"writes a {kind}'s folder"])
        if name and name != card.name:
            raise ScaffoldError(spec_card.SPEC, [f"name {card.name!r} is not the folder's "
                                                 f"{name!r}"])
        name, card_out, summary = card.name, card_text, card.summary
        examples = [(e.name, e.given, e.when, e.then, e.fixture) for e in card.examples]
    out = {spec_card.SPEC: card_out}
    if kind == "job":
        out["job.py"] = job_stub(card) if card is not None else _blank_job(name)
    else:
        out[f"{name}.py"] = app_stub(name, summary)
        out[MANIFEST] = manifest_text(name, summary)
    out[TEST_FILE[kind]] = stub_tests(kind, examples, name)
    out[CONFTEST] = template("conftest.py.template")
    out[AUTHORING] = authoring_text()
    return out


def _blank_job(name: str) -> str:
    """`job.py` for a blank card: a valid declaration to replace from spec.yml once its
    questions are answered (the class must declare a valid `JobMeta` to be defined at all)."""
    return template("blank_job.py.template").replace("@@NAME@@", name).replace(
        "@@CLASS@@", class_name(name))


# ── writing the folder ───────────────────────────────────────────────────────────────────────

def refuse_occupied(folder: str) -> None:
    """`ScaffoldError` naming *folder* when it exists and is not an empty folder."""
    if os.path.islink(folder):
        raise ScaffoldError(folder, ["is a symbolic link; a job's folder is a folder"])
    if os.path.exists(folder):
        if not os.path.isdir(folder):
            raise ScaffoldError(folder, ["exists and is a file, not a folder"])
        held = sorted(os.listdir(folder))
        if held:
            shown = ", ".join(held[:5]) + (", ..." if len(held) > 5 else "")
            raise ScaffoldError(folder, [f"exists and is not empty ({len(held)} entries: "
                                         f"{shown}); a new job's folder is new or empty"])


def write(folder: str, contents: dict) -> list:
    """Write *contents* into *folder* (refused when it exists and is not empty); answer the
    paths written."""
    refuse_occupied(folder)
    os.makedirs(folder, exist_ok=True)
    written = []
    for name, text in contents.items():
        path = os.path.join(folder, name)
        with open(path, "x", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        written.append(path)
    return written


def new(folder, kind: str, *, card_text: str = None, blank: bool = False) -> list:
    """Write a new *kind* folder at *folder* (its last part names it with *blank*)."""
    folder = os.fspath(folder)
    name = os.path.basename(os.path.normpath(folder)) if blank else ""
    return write(folder, files(kind, name=name, card_text=card_text, blank=blank))


